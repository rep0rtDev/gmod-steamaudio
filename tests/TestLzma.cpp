std::vector<uint8_t> RefPlain()
{
    std::vector<uint8_t> v;
    for (int rep = 0; rep < 4; ++rep)
        for (int i = 0; i < 256; ++i)
            v.push_back(static_cast<uint8_t>(i));
    const char* phrase = "hello source engine ";
    for (int rep = 0; rep < 20; ++rep)
        v.insert(v.end(), phrase, phrase + std::strlen(phrase));
    return v;
}

