SA_TEST(Lzma_DecodesReferenceStream)
{
    const std::vector<uint8_t> expected = RefPlain();
    std::vector<uint8_t> out;
    std::string err;
    SA_CHECK(lzma::DecompressRaw(kRefProps, kRefRaw, sizeof(kRefRaw), expected.size(), out, &err));
    SA_CHECK(err.empty());
    SA_CHECK(out == expected);
}

SA_TEST(Lzma_LiteralEncoderRoundTrips)
{
    std::vector<uint8_t> plain;
    for (int i = 0; i < 5000; ++i)
        plain.push_back(static_cast<uint8_t>((i * 7919) ^ (i >> 3)));
    const std::vector<uint8_t> blob = satest::LzmaLiteralEncoder::SourceBlob(plain);
    SA_CHECK(lzma::IsSourceCompressed(blob.data(), blob.size()));

    lzma::SourceHeader h;
    SA_CHECK(lzma::ReadSourceHeader(blob.data(), blob.size(), h));
    SA_CHECK_EQ(h.actualSize, uint32_t(5000));
    SA_CHECK_EQ(h.lzmaSize, uint32_t(blob.size() - lzma::kSourceHeaderSize));

    std::vector<uint8_t> out;
    std::string err;
    SA_CHECK(lzma::DecompressSource(blob.data(), blob.size(), out, &err));
    SA_CHECK(err.empty());
    SA_CHECK(out == plain);

    // Empty payload is legal and yields an empty buffer.
    const std::vector<uint8_t> emptyBlob = satest::LzmaLiteralEncoder::SourceBlob({});
    SA_CHECK(lzma::DecompressSource(emptyBlob.data(), emptyBlob.size(), out, &err));
    SA_CHECK(out.empty());
}

SA_TEST(Lzma_RejectsMalformedInput)
{
    std::vector<uint8_t> plain(300, 0x42);
    std::vector<uint8_t> blob = satest::LzmaLiteralEncoder::SourceBlob(plain);
    std::vector<uint8_t> out;
    std::string err;

    // Not a Source header at all.
    std::vector<uint8_t> junk(64, 0x11);
    SA_CHECK(!lzma::IsSourceCompressed(junk.data(), junk.size()));
    SA_CHECK(!lzma::DecompressSource(junk.data(), junk.size(), out, &err));
    SA_CHECK(!err.empty());

    // Header truncated.
    SA_CHECK(!lzma::IsSourceCompressed(blob.data(), 8));
    SA_CHECK(!lzma::DecompressSource(blob.data(), 8, out, &err));

    // lzmaSize larger than the data actually present.
    SA_CHECK(!lzma::DecompressSource(blob.data(), blob.size() - 10, out, &err));

    // Output cap enforced.
    SA_CHECK(!lzma::DecompressSource(blob.data(), blob.size(), out, &err, 100));

    // actualSize inflated beyond what the stream encodes -> must not succeed
    // and must not read past the input.
    std::vector<uint8_t> inflated = blob;
    const uint32_t big = 100000;
    std::memcpy(inflated.data() + 4, &big, 4);
    SA_CHECK(!lzma::DecompressSource(inflated.data(), inflated.size(), out, &err));

    // Corrupt range-coder bytes: decoder either errors or produces wrong
    // output, but never crashes.
    std::vector<uint8_t> corrupt = blob;
    for (size_t i = lzma::kSourceHeaderSize + 1; i < corrupt.size(); i += 3)
        corrupt[i] ^= 0xA5;
    lzma::DecompressSource(corrupt.data(), corrupt.size(), out, &err);
}
